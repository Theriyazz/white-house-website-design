// Writes src/data/image-manifest.ts: slot name -> public path for every image in
// public/images. Runs before dev and build, so the site never reads the
// filesystem at request time. Run `npm run images` after adding images.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "public", "images");
const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

const manifest = {};
for (const file of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  const { name, ext } = path.parse(file);
  if (exts.has(ext.toLowerCase())) manifest[name] = `/images/${file}`;
}

const out = path.join(root, "src", "data", "image-manifest.ts");
fs.writeFileSync(
  out,
  `// Generated by scripts/image-manifest.mjs. Do not edit by hand.\n` +
    `export const imageManifest: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(`image manifest: ${Object.keys(manifest).length} images`);
